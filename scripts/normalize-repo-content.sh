PY

mkdir -p partitions
if [[ -f partitions/esp32-c3-multi-v7.3.4.2-partitions.csv && ! -f partitions/esp32-c3-multi-partitions.csv ]]; then
  cp partitions/esp32-c3-multi-v7.3.4.2-partitions.csv partitions/esp32-c3-multi-partitions.csv
fi

mkdir -p secrets
if [[ ! -f secrets/secrets-example.yaml ]]; then
  cat > secrets/secrets-example.yaml <<'EOF2'
# Copy to secrets.yaml locally and fill in real values.
wifi_ssid: "YOUR_WIFI_SSID"
wifi_password: "YOUR_WIFI_PASSWORD"
gateway_mgmt_username: "admin"
gateway_mgmt_password: "change-me"
EOF2
fi

./scripts/generate-header.sh

echo
echo "Normalization complete. Recommended next steps:"
echo "  git status"
echo "  ./scripts/preflight.sh"
echo "  esphome compile firmware/esp32-c3-multi-sensor.yaml"
