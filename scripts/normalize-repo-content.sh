echo "preflight: PASS"
SH
chmod +x scripts/preflight.sh

python3 <<'PY'
from pathlib import Path

p = Path('firmware/esp32-c3-multi-sensor.yaml')
text = p.read_text(encoding='utf-8')
replacements = {
    'dashboard-v7.3.4.2.h': '../dashboard/dashboard.h',
    'sensor_history_multi-v7.3.4.2.h': '../dashboard/sensor_history_multi.h',
    'esp32-c3-multi-v7.3.4.2-partitions.csv': '../partitions/esp32-c3-multi-partitions.csv',
    'esp32-c3-multi-sensor-v7.3.4.2.yaml': 'firmware/esp32-c3-multi-sensor.yaml',
    'dashboard-v7.3.4.2.html': 'dashboard/dashboard.html',
    'dashboard-v7.3.4.2.js': 'dashboard/dashboard.js',
    'dashboard-v7.3.4.2.h': '../dashboard/dashboard.h',
    'sensor_history_multi-v7.3.4.2.h': '../dashboard/sensor_history_multi.h',
    'esp32-c3-multi-v7.3.4.2-partitions.csv': '../partitions/esp32-c3-multi-partitions.csv',
    'generate-header-v7.3.4.2.sh': 'scripts/generate-header.sh',
    'secrets-example-v7.3.4.2.yaml': 'secrets/secrets-example.yaml',
